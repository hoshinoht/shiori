// checkD43Mutation compares a mutation vector with the D.4.3 additions on
// and off (all earlier changes on in both runs).
func checkD43Mutation(t *testing.T, v *mutationVector) string {
	t.Helper()
	saved := IDSource
	IDSource = nil
	defer func() { IDSource = saved }()
	on := d43RunMutation(t, v, false)
	off := d43RunMutation(t, v, true)
	if on.auths != off.auths || (on.err == nil) != (off.err == nil) {
		t.Fatalf("D.4.3 authorizations/errors differ: %d/%v vs %d/%v", on.auths, on.err, off.auths, off.err)
	}
	if on.err != nil {
		if on.root.Normalize(on.err.Error()) != off.root.Normalize(off.err.Error()) {
			t.Fatalf("D.4.3 error text differs: %v vs %v", on.err, off.err)
		}
		if _, listed := d43Expectations(t)[v.ID]; listed && !d43Update() {
			t.Fatalf("listed in %s but identical with D.4.3 off; remove the entry", d43ExpectationsFile)
		}
		return ""
	}
	keys := func(m map[string][]byte) []string {
		var out []string
		for k := range m {
			out = append(out, k)
		}
		sort.Strings(out)
		return out
	}
	if !reflect.DeepEqual(keys(on.files), keys(off.files)) {
		t.Fatalf("D.4.3 changed-file sets differ: %v vs %v", keys(on.files), keys(off.files))
	}
	for k, b := range on.files {
		if !bytes.Equal(b, off.files[k]) {
			t.Fatalf("D.4.3 changed %s", k)
		}
	}
	got, want := on.root.Normalize(on.out.String()), off.root.Normalize(off.out.String())
	_, listed := d43Expectations(t)[v.ID]
	if got == want {
		if listed && !d43Update() {
			t.Fatalf("listed in %s but identical with D.4.3 off; remove the entry", d43ExpectationsFile)
		}
		return ""
	}
	if v.Call.Tool != "workplan_checkpoint" {
		t.Fatalf("D.4.3 changed a %s result", v.Call.Tool)
	}
	ws, ok := on.out.Value.Get("warnings")
	if !ok {
		t.Fatalf("D.4.3 checkpoint result differs without warnings")
	}
	inv := string(ojson.Pretty(objWithout(on.out.Value, "warnings")))
	if on.root.Normalize(inv) != want {
		t.Fatalf("D.4.3 result minus warnings differs\n%s", firstDiff(on.root.Normalize(inv), want))
	}
	restated := d43RestateWarnings(t, v)
	var gotW []string
	for _, x := range ws.Elems() {
		gotW = append(gotW, x.Str())
	}
	if !reflect.DeepEqual(gotW, restated) {
		t.Fatalf("warnings %q, restated %q", gotW, restated)
	}
	return d43Pin(t, v.ID, "checkpoint drop warnings", got, ojson.UTF16Len(on.out.String()), true)
}

// d43RestateWarnings restates contracts §18 item 2 from the fixture's
// stored checkpoint and the vector input (no merge in the corpus): each
// list whose stored entries are not all in the new list, in the order
// guardrails, references, recentValidation, blockers.
func d43RestateWarnings(t *testing.T, v *mutationVector) []string {
	t.Helper()
	var in map[string]any
	json.Unmarshal(v.Call.Input, &in)
	id, _ := in["id"].(string)
	data, err := os.ReadFile(testutil.Testdata("fixtures", v.Fixture, ".opencode/workplan", id+".checkpoint.json"))
	if err != nil {
		t.Fatalf("restating warnings: %v", err)
	}
	var cp map[string]any
	if err := json.Unmarshal(data, &cp); err != nil {
		t.Fatal(err)
	}
	strs := func(x any) []string {
		var out []string
		seen := map[string]bool{}
		l, _ := x.([]any)
		for _, e := range l {
			s := strings.TrimSpace(e.(string))
			if s != "" && !seen[s] {
				seen[s] = true
				out = append(out, s)
			}
		}
		return out
	}
	var out []string
	for _, k := range []string{"guardrails", "references", "recentValidation", "blockers"} {
		var before []string // the stored list as stored
		if l, ok := cp[k].([]any); ok {
			for _, e := range l {
				before = append(before, e.(string))
			}
		}
		now := strs(in[k])
		kept := map[string]bool{}
		for _, x := range now {
			kept[x] = true
		}
		n := 0
		for _, x := range before {
			if !kept[x] {
				n++
			}
		}
		if n == 0 {
			continue
		}
		noun := "entries"
		if n == 1 {
			noun = "entry"
		}
		out = append(out, fmt.Sprintf("%s: %d → %d (%d previous %s not kept; merge=true keeps omitted fields)", k, len(before), len(now), n, noun))
	}
	return out
}
