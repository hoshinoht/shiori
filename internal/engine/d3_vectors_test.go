// D.3 approved design changes (contracts §13, 2026-09-30). The oracle
// corpus stays untouched. Read-path vectors are judged like D.2: the same
// engine with the D.3 additions turned off (noD3) must pass every earlier
// check unchanged, and the D.3 output must (a) turn back into the D.3-off
// output byte-for-byte when the approved members are removed, and (b)
// carry additions that an independent restatement from the fixture's raw
// bytes confirms (raw-byte hashes, stale checkpoint detail, missing step
// markers). Mutation vectors that D.3 changes have dedicated comparators
// below. Every D.3 vector is pinned in testdata/d3/expectations.json.
//
// SHIORI_D3_UPDATE=1 rewrites the expectation hashes (review the diff).

const d3ExpectationsFile = "d3/expectations.json"

var (
	d3Once    sync.Once
	d3Loaded  d1File
	d3Mu      sync.Mutex
	d3Updated = map[string]d1Expectation{}
)

func d3Update() bool { return os.Getenv("SHIORI_D3_UPDATE") == "1" }

func d3Expectations(t testing.TB) map[string]d1Expectation {
	d3Once.Do(func() {
		data, err := os.ReadFile(testutil.Testdata(d3ExpectationsFile))
		if err == nil {
			err = json.Unmarshal(data, &d3Loaded)
		}
		if err != nil && !d3Update() {
			t.Fatalf("reading %s: %v", d3ExpectationsFile, err)
		}
		if d3Loaded.Vectors == nil {
			d3Loaded.Vectors = map[string]d1Expectation{}
		}
	})
	return d3Loaded.Vectors
}

func d3Write(t *testing.T, prefixes ...string) {
	if !d3Update() {
		return
	}
	cur := d3Expectations(t)
	out := map[string]d1Expectation{}
	for id, x := range cur {
		owned := false
		for _, p := range prefixes {
			owned = owned || strings.HasPrefix(id, p)
		}
		if !owned {
			out[id] = x
		}
	}
	d3Mu.Lock()
	for id, x := range d3Updated {
		owned := false
		for _, p := range prefixes {
			owned = owned || strings.HasPrefix(id, p)
		}
		if owned {
			out[id] = x
		}
	}
	d3Mu.Unlock()
	f := d1File{
		Note:    "D.3 approved design changes (docs/contracts.md §13): oracle vectors whose Go output changes on purpose, with the SHA-256 and UTF-16 length of the pinned Go output (root-normalized; for a refusal, of the error text). Generated by SHIORI_D3_UPDATE=1 go test ./internal/engine; read vectors also pass a comparator against the same engine with the D.3 additions off, mutation vectors a dedicated comparator against the oracle.",
		Vectors: out,
	}
	data, _ := json.MarshalIndent(f, "", "  ")
	if err := os.MkdirAll(testutil.Testdata("d3"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(testutil.Testdata(d3ExpectationsFile), append(data, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
	d3Loaded.Vectors = out
	t.Logf("wrote %s (%d vectors)", d3ExpectationsFile, len(out))
}

// d3Pin records (update mode) or checks the pinned output of a D.3 vector.
func d3Pin(t *testing.T, id, change, normalized string, rawLen int, checkLen bool) string {
	t.Helper()
	if d3Update() {
		d3Mu.Lock()
		d3Updated[id] = d1Expectation{Change: change, OutputSha256: sha(normalized), RawOutputLength: rawLen}
		d3Mu.Unlock()
		return id + ": D.3 " + change + " (recorded)"
	}
	x, ok := d3Expectations(t)[id]
	if !ok {
		t.Fatalf("output differs on purpose (D.3) but the vector is not listed in %s", d3ExpectationsFile)
	}
	if sha(normalized) != x.OutputSha256 {
		t.Fatalf("D.3 pinned output changed: sha %s want %s (SHIORI_D3_UPDATE=1 to re-pin after review)", sha(normalized), x.OutputSha256)
	}
	if checkLen && rawLen != x.RawOutputLength {
		t.Fatalf("D.3 raw length %d want %d", rawLen, x.RawOutputLength)
	}
	return id + ": D.3 " + x.Change
}

// d3Change names the D.3 items a read output carries.
func d3Change(tool, text string) string {
	var items []string
	add := func(ok bool, item string) {
		if ok {
			items = append(items, item)
		}
	}
	add(tool == "workplan_list", "5 list issues array")
	add(rawHashesPresent(tool, text), "2 raw-byte hashes")
	add(strings.Contains(text, "stale-markdown"), "3 stale Markdown copy")
	add(strings.Contains(text, d3MarkerNeedle), "4 missing step markers")
	add(strings.Contains(text, msgStale+". "), "5 stale checkpoint detail")
	return "items " + strings.Join(items, ", ")
}

// rawHashesPresent reports an entry that carries raw-byte hashes (an
// unreadable plan: hashes without a workplan summary).
func rawHashesPresent(tool, text string) bool {
	var doc map[string]any
	if json.Unmarshal([]byte(text), &doc) != nil {
		return false
	}
	raw := func(e map[string]any) bool {
		_, w := e["workplan"]
		_, k := e["kind"]
		_, p := e["path"]
		_, h := e["planHash"]
		return h && !w && !k && !p
	}
	switch tool {
	case "workplan_validate":
		return raw(doc)
	case "workplan_doctor":
		for _, p := range asList(doc["plans"]) {
			if raw(p.(map[string]any)) {
				return true
			}
		}
	case "workplan_list":
		for _, p := range asList(doc["workplans"]) {
			if raw(p.(map[string]any)) {
				return true
			}
		}
	}
	return false
}

func d3Candidate(t *testing.T, v *vector, text, offText string) bool {
	_, listed := d3Expectations(t)[v.ID]
	return listed || text != offText
}

func checkD3(t *testing.T, v *vector, root testutil.Root, text, offText string) string {
	t.Helper()
	if text == offText {
		t.Fatalf("listed in %s but identical to the D.3-off output; remove the entry", d3ExpectationsFile)
	}
	inv, err := d3Inverse(v.Call.Tool, text)
	if err != nil {
		t.Fatalf("D.3 comparator: %v", err)
	}
	if inv != offText {
		t.Fatalf("D.3 output minus the approved members differs from the D.3-off output\n%s", firstDiff(inv, offText))
	}
	if err := d3Restate(root.Path, v, text); err != nil {
		t.Fatalf("D.3 restatement: %v", err)
	}
	change := d3Change(v.Call.Tool, text)
	return d3Pin(t, v.ID, change, root.Normalize(text), ojson.UTF16Len(text), root.SameLength())
}

// ---- inverse: remove exactly the approved D.3 members ----

func objWithout(v ojson.Value, keys ...string) ojson.Value {
	drop := map[string]bool{}
	for _, k := range keys {
		drop[k] = true
	}
	var out []ojson.Member
	for _, m := range v.Members() {
		if !drop[m.Key] {
			out = append(out, m)
		}
	}
	return ojson.ObjectValue(out)
}

func objReplace(v ojson.Value, key string, nv ojson.Value) ojson.Value {
	out := append([]ojson.Member(nil), v.Members()...)
	for i := range out {
		if out[i].Key == key {
			out[i].Value = nv
		}
	}
	return ojson.ObjectValue(out)
}

func has3(v ojson.Value, key string) bool { _, ok := v.Get(key); return ok }

const d3MarkerNeedle = "has no step marker (<!-- workplan-step-id: <stepId> -->)"

// withoutMarkerWarning drops the D.3 step-marker warning; the member goes
// when nothing else is left in it.
func withoutMarkerWarning(v ojson.Value) ojson.Value {
	w, ok := v.Get("warnings")
	if !ok {
		return v
	}
	var keep []string
	for _, x := range w.Elems() {
		if !strings.Contains(x.Str(), d3MarkerNeedle) {
			keep = append(keep, x.Str())
		}
	}
	if len(keep) == 0 {
		return objWithout(v, "warnings")
	}
	return objReplace(v, "warnings", ojson.StringsValue(keep))
}

func withoutRawHashes(v ojson.Value) ojson.Value {
	if has3(v, "workplan") || has3(v, "path") || !has3(v, "planHash") || !has3(v, "stateHash") {
		return v
	}
	return objWithout(v, "planHash", "stateHash")
}

func d3Inverse(tool, text string) (string, error) {
	parsed, err := ojson.Parse([]byte(text))
	if err != nil {
		return "", err
	}
	v := parsed.Value
	switch tool {
	case "workplan_validate":
		v = withoutMarkerWarning(withoutRawHashes(v))
	case "workplan_list":
		ws, _ := v.Get("workplans")
		var out []ojson.Value
		for _, p := range ws.Elems() {
			if !has3(p, "kind") {
				issues, _ := p.Get("issues")
				if len(issues.Elems()) != 1 {
					return "", fmt.Errorf("invalid list entry needs exactly one issue: %s", ojson.Compact(p))
				}
				id, _ := p.Get("id")
				valid, _ := p.Get("valid")
				p = ojson.NewObject(3).Set("id", id).Set("valid", valid).Set("issue", issues.Elems()[0]).Value()
			}
			out = append(out, p)
		}
		v = objReplace(v, "workplans", ojson.ArrayValue(out))
	case "workplan_doctor":
		plans, _ := v.Get("plans")
		var out []ojson.Value
		for _, p := range plans.Elems() {
			p = withoutMarkerWarning(withoutRawHashes(p))
			if issues, ok := p.Get("issues"); ok {
				var is []string
				for _, x := range issues.Elems() {
					s := x.Str()
					if pre := "checkpoint: " + msgStale + ". "; strings.HasPrefix(s, pre) {
						s = "checkpoint: " + msgStale
					}
					is = append(is, s)
				}
				p = objReplace(p, "issues", ojson.StringsValue(is))
			}
			out = append(out, p)
		}
		v = objReplace(v, "plans", ojson.ArrayValue(out))
		if strays, ok := v.Get("strayArtifacts"); ok {
			if om, _ := v.Get("omittedStrayArtifacts"); om.NumberLiteral() != "0" {
				return "", fmt.Errorf("stray inverse with omitted entries is not supported")
			}
			var keep []ojson.Value
			for _, s := range strays.Elems() {
				if k, _ := s.Get("kind"); k.Str() != "stale-markdown" {
					keep = append(keep, s)
				}
			}
			var warn []string
			w, _ := v.Get("warnings")
			for _, x := range w.Elems() {
				if !strings.HasPrefix(x.Str(), "Stale Markdown copy ") {
					warn = append(warn, x.Str())
				}
			}
			if len(keep) == 0 {
				v = objWithout(v, "strayArtifacts", "strayArtifactCount", "omittedStrayArtifacts", "warnings")
			} else {
				v = objReplace(v, "strayArtifacts", ojson.ArrayValue(keep))
				v = objReplace(v, "strayArtifactCount", ojson.IntValue(int64(len(keep))))
				v = objReplace(v, "warnings", ojson.StringsValue(warn))
			}
		}
	default:
		return "", fmt.Errorf("no D.3 inverse for %s", tool)
	}
	return string(ojson.Pretty(v)), nil
}

// ---- independent restatement from raw fixture bytes ----

func fileSHA(path string) (string, bool) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", false
	}
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:]), true
}

// restateRawHashes recomputes the D.3 raw-byte hashes of an unreadable
// plan straight from the hash contract (contracts §3): the primary JSON,
// plus the three sidecars for the state hash, sorted by path.
func restateRawHashes(root, id string) (string, string) {
	type entry struct{ path, sha string }
	rel := func(suffix string) string { return ".opencode/workplan/" + id + suffix }
	get := func(r string) entry {
		s, ok := fileSHA(filepath.Join(root, r))
		if !ok {
			return entry{r, ""}
		}
		return entry{r, s}
	}
	manifest := func(es []entry) string {
		sort.Slice(es, func(i, j int) bool { return es[i].path < es[j].path })
		var parts []string
		for _, e := range es {
			if e.sha == "" {
				parts = append(parts, fmt.Sprintf(`{"path":%q,"missing":true}`, e.path))
			} else {
				parts = append(parts, fmt.Sprintf(`{"path":%q,"sha256":%q}`, e.path, e.sha))
			}
		}
		return "[" + strings.Join(parts, ",") + "]"
	}
	h := func(version, m string) string {
		sum := sha256.Sum256([]byte(version + "\n" + m + "\n"))
		return hex.EncodeToString(sum[:])
	}
	plan := []entry{get(rel(".json"))}
	state := []entry{get(rel(".json")), get(rel(".checkpoint.json")), get(rel(".dependencies.json")), get(rel(".transaction.json"))}
	return h("workplan-plan-v1", manifest(plan)), h("workplan-state-v1", manifest(state))
}

var staleChanged = regexp.MustCompile(`(\S+) changed \(checkpoint `)

func d3Restate(root string, v *vector, text string) error {
	var doc map[string]any
	if err := json.Unmarshal([]byte(text), &doc); err != nil {
		return err
	}
	var in struct {
		ID string `json:"id"`
	}
	json.Unmarshal(v.Call.Input, &in)
	checkRaw := func(id string, e map[string]any) error {
		ph, _ := e["planHash"].(string)
		sh, _ := e["stateHash"].(string)
		wp, wsh := restateRawHashes(root, id)
		if ph != wp || sh != wsh {
			return fmt.Errorf("%s: raw hashes %s/%s, restated %s/%s", id, ph, sh, wp, wsh)
		}
		return nil
	}
	checkEntry := func(id string, e map[string]any) error {
		if _, ok := e["workplan"]; !ok {
			if _, ok := e["planHash"]; ok {
				if err := checkRaw(id, e); err != nil {
					return err
				}
			}
			return nil
		}
		for _, x := range asList(e["issues"]) {
			s, _ := x.(string)
			if !strings.HasPrefix(s, "checkpoint: "+msgStale+". ") {
				continue
			}
			if err := restateStale(root, id, s); err != nil {
				return err
			}
		}
		for _, x := range asList(e["warnings"]) {
			s, _ := x.(string)
			if strings.Contains(s, d3MarkerNeedle) {
				if err := restateMarkers(root, id, s); err != nil {
					return err
				}
			}
		}
		return nil
	}
	switch v.Call.Tool {
	case "workplan_validate":
		if _, ok := doc["path"]; !ok {
			if _, ok := doc["planHash"]; ok {
				return checkRaw(strings.ToLower(in.ID), doc)
			}
			return nil
		}
		for _, x := range asList(doc["warnings"]) {
			s, _ := x.(string)
			if strings.Contains(s, d3MarkerNeedle) {
				if err := restateMarkers(root, strings.ToLower(in.ID), s); err != nil {
					return err
				}
			}
		}
	case "workplan_doctor":
		for _, p := range asList(doc["plans"]) {
			e := p.(map[string]any)
			if err := checkEntry(e["id"].(string), e); err != nil {
				return err
			}
		}
	case "workplan_list":
		for _, p := range asList(doc["workplans"]) {
			e := p.(map[string]any)
			if _, ok := e["kind"]; ok {
				continue
			}
			if _, ok := e["issue"]; ok {
				return fmt.Errorf("list entry still has the D.1 issue string")
			}
			if _, ok := e["planHash"]; ok {
				if err := checkRaw(e["id"].(string), e); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func asList(x any) []any { l, _ := x.([]any); return l }

// restateStale checks that the stale detail names exactly the checkpoint
// manifest entries whose bytes differ now.
func restateStale(root, id, issue string) error {
	var cp struct {
		Manifest []struct {
			Path    string `json:"path"`
			SHA256  string `json:"sha256"`
			Missing bool   `json:"missing"`
		} `json:"manifest"`
	}
	data, err := os.ReadFile(filepath.Join(root, ".opencode/workplan", id+".checkpoint.json"))
	if err != nil {
		return err
	}
	if err := json.Unmarshal(data, &cp); err != nil {
		return err
	}
	var want []string
	for _, en := range cp.Manifest {
		now, ok := fileSHA(filepath.Join(root, en.Path))
		if en.Missing != !ok || (ok && now != en.SHA256) {
			want = append(want, en.Path)
		}
	}
	var got []string
	for _, m := range staleChanged.FindAllStringSubmatch(issue, -1) {
		got = append(got, m[1])
	}
	sort.Strings(want)
	sort.Strings(got)
	if !reflect.DeepEqual(got, want) {
		return fmt.Errorf("%s: stale detail names %v, restated %v", id, got, want)
	}
	return nil
}

var markerCount = regexp.MustCompile(`for (\d+) of (\d+) steps: `)

// restateMarkers counts the steps whose marker is absent from the linked
// Markdown, from the raw plan JSON and Markdown text.
func restateMarkers(root, id, warning string) error {
	var plan struct {
		PlanFile string `json:"planFile"`
		Phases   []struct {
			ID    string `json:"id"`
			Steps []struct {
				ID string `json:"id"`
			} `json:"steps"`
		} `json:"phases"`
	}
	data, err := os.ReadFile(filepath.Join(root, ".opencode/workplan", id+".json"))
	if err != nil {
		return err
	}
	if err := json.Unmarshal(data, &plan); err != nil {
		return err
	}
	md, err := os.ReadFile(filepath.Join(root, plan.PlanFile))
	if err != nil {
		return err
	}
	missing, total := 0, 0
	for _, ph := range plan.Phases {
		for _, st := range ph.Steps {
			total++
			if !strings.Contains(string(md), "<!-- workplan-step-id: "+st.ID+" -->") {
				missing++
			}
		}
	}
	m := markerCount.FindStringSubmatch(warning)
	if m == nil || m[1] != fmt.Sprint(missing) || m[2] != fmt.Sprint(total) {
		return fmt.Errorf("%s: marker warning %q, restated %d of %d", id, warning, missing, total)
	}
	return nil
}

