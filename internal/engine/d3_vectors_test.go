// hashesMatchDisk checks the output hashes against the committed files.
func hashesMatchDisk(t *testing.T, root, id string, out Output) {
	t.Helper()
	s, err := snapshot.Load(root, id, snapshot.DefaultLimits)
	if err != nil {
		t.Fatal(err)
	}
	ph, _ := out.Value.Get("planHash")
	sh, _ := out.Value.Get("stateHash")
	if ph.Str() != s.PlanHash || sh.Str() != s.StateHash {
		t.Fatalf("output hashes %s/%s, disk %s/%s", ph.Str(), sh.Str(), s.PlanHash, s.StateHash)
	}
}

func checkResetDraftD3(t *testing.T, v *mutationVector, root testutil.Root, e *Engine) {
	dir := filepath.Join(root.Path, ".opencode", "workplan")
	var in struct {
		ID string `json:"id"`
	}
	json.Unmarshal(v.Call.Input, &in)
	before := decodeJSONFile(t, filepath.Join(dir, in.ID+".json"))
	beforeFiles := snapshotFiles(t, root.Path)
	out, err, n := runVectorMutation(t, v, e)
	if err != nil {
		t.Fatal(err)
	}
	if n != 1 {
		t.Fatalf("authorizations %d, want 1", n)
	}
	outputExcept(t, v, root.Normalize(out.String()), []string{"phaseCount", "stepCount", "openFindingCount"}, []string{"planHash", "stateHash", "checkpointRemoved"})
	// Restate the expected JSON: the before document with every status
	// set to draft and updatedAt at the frozen clock.
	want := before
	want["status"] = "draft"
	want["updatedAt"] = frozen.Format("2006-01-02T15:04:05.000Z")
	phases := asList(want["phases"])
	steps, open := 0, 0
	for _, ph := range phases {
		pm := ph.(map[string]any)
		pm["status"] = "draft"
		for _, st := range asList(pm["steps"]) {
			st.(map[string]any)["status"] = "draft"
			steps++
		}
	}
	for _, f := range asList(want["reviewFindings"]) {
		if f.(map[string]any)["status"] != "resolved" {
			open++
		}
	}
	after := decodeJSONFile(t, filepath.Join(dir, in.ID+".json"))
	if !reflect.DeepEqual(after, want) {
		t.Fatalf("draft reset JSON is not the status-only reset of the stored plan")
	}
	wp, _ := out.Value.Get("workplan")
	for k, n := range map[string]int{"phaseCount": len(phases), "stepCount": steps, "openFindingCount": open} {
		if x, _ := wp.Get(k); x.NumberLiteral() != fmt.Sprint(n) {
			t.Fatalf("%s %s, restated %d", k, x.NumberLiteral(), n)
		}
	}
	hashesMatchDisk(t, root.Path, in.ID, out)
	// The Markdown was generated, so it follows the JSON; the checkpoint
	// (if any) is removed; nothing else changes.
	s, _ := snapshot.Load(root.Path, in.ID, snapshot.DefaultLimits)
	if gen, _ := e.generatedMarkdown(s); !gen {
		t.Fatal("generated Markdown was not regenerated")
	}
	afterFiles := snapshotFiles(t, root.Path)
	allowed := map[string]bool{".opencode/workplan/" + in.ID + ".json": true, s.Plan.PlanFile: true, ".opencode/workplan/" + in.ID + ".checkpoint.json": true}
	for k, b := range beforeFiles {
		if a, ok := afterFiles[k]; (!ok || a != b) && !allowed[k] {
			t.Fatalf("unexpected change %s", k)
		}
	}
	if _, ok := afterFiles[".opencode/workplan/"+in.ID+".checkpoint.json"]; ok {
		t.Fatal("checkpoint not removed")
	}
	t.Log(d3Pin(t, v.ID, "item 1 draft reset keeps structure", root.Normalize(out.String()), ojson.UTF16Len(out.String()), false))
}

