func decodeJSONFile(t *testing.T, path string) map[string]any {
	t.Helper()
	var m map[string]any
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	d := json.NewDecoder(strings.NewReader(string(data)))
	d.UseNumber()
	if err := d.Decode(&m); err != nil {
		t.Fatal(err)
	}
	return m
}

// outputExcept compares a mutation output with the oracle output after
// deleting the named workplan-summary members and top-level members.
func outputExcept(t *testing.T, v *mutationVector, got string, summary []string, top []string) {
	t.Helper()
	g, err := decodeAny(got)
	if err != nil {
		t.Fatal(err)
	}
	var w any
	d := json.NewDecoder(strings.NewReader(string(v.Expect.Output)))
	d.UseNumber()
	d.Decode(&w)
	gm, wm := g.(map[string]any), w.(map[string]any)
	for _, m := range []map[string]any{gm, wm} {
		for _, k := range top {
			delete(m, k)
		}
		if s, ok := m["workplan"].(map[string]any); ok {
			for _, k := range summary {
				delete(s, k)
			}
		}
	}
	if !reflect.DeepEqual(gm, wm) {
		gb, _ := json.Marshal(gm)
		wb, _ := json.Marshal(wm)
		t.Fatalf("output differs beyond the D.3 members\n got %s\nwant %s", gb, wb)
	}
}

